# Week 2 - Calculator Functions
# This file stores reusable calculator functions.

def add_numbers(first_number, second_number):
    return first_number + second_number

def subtract_numbers(first_number, second_number):
    return first_number - second_number

def multiply_numbers(first_number, second_number):
    return first_number * second_number

def divide_numbers(first_number, second_number):
    return first_number / second_number

def calculate_average(first_number, second_number):
    return (first_number + second_number) / 2

def calculate_percentage(first_number, second_number):
    return (first_number / second_number) * 100